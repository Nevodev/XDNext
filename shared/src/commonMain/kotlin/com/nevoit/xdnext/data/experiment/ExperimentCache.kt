package com.nevoit.xdnext.data.experiment

import com.nevoit.xdnext.core.log.appLog
import com.nevoit.xdnext.data.fetch.FetchResult
import kotlinx.serialization.json.Json
import okio.FileSystem
import okio.Path
import kotlin.time.Instant

/**
 * The experiment list's on-disk cache: `PhysicsExperiment.json` in the support directory.
 *
 * The original's own file name, in the same place, for the reason
 * [com.nevoit.xdnext.data.timetable.TimetableCache] keeps `ClassTable.json`: a captured file should be
 * recognisable. The *contents* are this port's own shape where the original's were generated by
 * `json_serializable` over a Dart record type, which wrote each time range as untyped JSON — a bare
 * [ExperimentEntry] list is what a reader can actually decode, and the score's own fields
 * (`label`/`found`/`rawUrl`) are the original's names.
 *
 * The freshness stamp is the file's **modification time**, not a field inside it — the convention every
 * cache in this app follows, and the one that makes a copied file unable to lie about its age.
 *
 * A read that fails is a cache *miss*, never an error: the lab site is reachable only from the campus
 * network, so an unreadable file has to degrade to "ask again" rather than to a page that cannot draw
 * the experiments it is holding.
 */
class ExperimentCache(
    private val fileSystem: FileSystem,
    private val directory: Path,
    private val json: Json,
) {

    private val path: Path = directory / PHYSICS_EXPERIMENT_FILE

    /** The cached experiments, or null when there are none to read. */
    fun read(): FetchResult<List<ExperimentEntry>>? {
        if (!fileSystem.exists(path)) return null
        appLog.i { "[ExperimentCache] Checking out cache from $PHYSICS_EXPERIMENT_FILE" }
        val text = runCatching { fileSystem.read(path) { readUtf8() } }
            .onFailure { appLog.w(it) { "Could not read $path" } }
            .getOrNull()
            ?: return null
        val data = runCatching { json.decodeFromString<List<ExperimentEntry>>(text) }
            .onFailure { appLog.w(it) { "Discarding unreadable $PHYSICS_EXPERIMENT_FILE" } }
            .getOrNull()
            ?: return null
        return FetchResult.cache(fetchTime = lastModified(), data = data)
    }

    /** Writes the experiment list, which is also what stamps its fetched-at time. */
    fun save(entries: List<ExperimentEntry>) {
        val encoded = runCatching { json.encodeToString(entries) }
            .onFailure { appLog.w(it) { "Could not encode the experiments for $PHYSICS_EXPERIMENT_FILE" } }
            .getOrNull()
            ?: return
        runCatching {
            fileSystem.createDirectories(directory)
            fileSystem.write(path) { writeUtf8(encoded) }
        }.onFailure {
            // Losing the cache degrades to "the next launch asks again", which is recoverable.
            appLog.w(it) { "Could not write $path" }
        }
    }

    private fun lastModified(): Instant {
        val millis = runCatching { fileSystem.metadata(path).lastModifiedAtMillis }.getOrNull()
        return Instant.fromEpochMilliseconds(millis ?: 0L)
    }

    /**
     * Forgets the cached list.
     *
     * Called when the credentials change: the list describes the account they were fetched for, and a
     * cached answer to a question about a different account is worse than no answer.
     */
    fun delete() {
        runCatching { fileSystem.delete(path) }
            .onFailure { appLog.w(it) { "Could not delete $path" } }
    }

    companion object {
        /** The original's own file name. */
        const val PHYSICS_EXPERIMENT_FILE = "PhysicsExperiment.json"
    }
}
